// Cihaz Dilini Akıllıca Otomatik Algılama (Localization Auto-Detect)
export function detectDeviceLanguage() {
  try {
    const saved = localStorage.getItem('neon_language');
    if (saved && TRANSLATIONS[saved]) return saved;

    const navLangs = navigator.languages || [navigator.language || navigator.userLanguage || 'en'];
    for (const lang of navLangs) {
      if (!lang) continue;
      const lower = lang.toLowerCase();
      if (lower.startsWith('tr')) return 'tr-TR';
      if (lower.startsWith('de')) return 'de-DE';
      if (lower.startsWith('ja')) return 'ja-JP';
      if (lower.startsWith('fr-ca')) return 'fr-CA';
      if (lower.startsWith('fr')) return 'fr-FR';
      if (lower.startsWith('zh-hk')) return 'zh-HK';
      if (lower.startsWith('zh-tw')) return 'zh-TW';
      if (lower.startsWith('zh')) return 'zh-CN';
      if (lower.startsWith('en')) return 'en-GB';
    }
  } catch (e) {}
  return 'en-GB';
}

// Aktif dil yöneticisi (Cihaz dili veya kaydedilmiş dil)
let currentLanguage = detectDeviceLanguage();
if (!TRANSLATIONS[currentLanguage]) {
  currentLanguage = 'en-GB';
}

export function getCurrentLanguage() {
  return currentLanguage;
}

export function t(key, params = {}) {
  const dict = TRANSLATIONS[currentLanguage] || TRANSLATIONS['en-GB'];
  let text = dict[key] || TRANSLATIONS['en-GB'][key] || key;
  for (const [k, v] of Object.entries(params)) {
    text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), v);
  }
  return text;
}

export function setLanguage(langCode) {
  if (!TRANSLATIONS[langCode]) return;
  currentLanguage = langCode;
  try {
    localStorage.setItem('neon_language', langCode);
  } catch (e) {}
  document.documentElement.lang = langCode.split('-')[0];
  applyTranslationsToDOM();
  if (window.game && typeof window.game.onLanguageChanged === 'function') {
    window.game.onLanguageChanged(langCode);
  }
}

export function applyTranslationsToDOM() {
  // data-i18n
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (key) {
      el.textContent = t(key);
    }
  });

  // data-i18n-html
  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    const key = el.getAttribute('data-i18n-html');
    if (key) {
      el.innerHTML = t(key);
    }
  });

  // data-i18n-title
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    const key = el.getAttribute('data-i18n-title');
    if (key) {
      el.setAttribute('title', t(key));
    }
  });

  // data-i18n-aria
  document.querySelectorAll('[data-i18n-aria]').forEach(el => {
    const key = el.getAttribute('data-i18n-aria');
    if (key) {
      el.setAttribute('aria-label', t(key));
    }
  });
}
